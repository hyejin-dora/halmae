# ===============================================================
#  실제 계산값을 섞어 넣기 위한 도우미
#     계산이 안 된 경우에도 화면이 깨지지 않도록 기본값을 둡니다.
# ===============================================================
def _facts(answers: dict | None, saju: dict | None, astro: dict | None) -> dict:
    from halmae_ai import career_context, relationship_context

    answers = answers or {}
    name = answers.get("이름") or "너"
    concern = answers.get("고민 분야") or "지금의 고민"
    # 관계 상태 — '연애·관계' 를 고른 사람에게만 값이 있습니다.
    # Mock 에서도 이 값을 실제로 써야, 개발 중에 화면이 진짜와 달라지지 않습니다.
    relationship = relationship_context(answers)
    # 커리어 상황 — '일·커리어' 를 고른 사람에게만 값이 있습니다. (같은 이유)
    career = career_context(answers)

    if saju:
        pillars = saju["기둥"]
        day_stem = saju["일간"]
        ohaeng = saju["오행 분포"]
        strongest = max(ohaeng, key=lambda k: ohaeng[k])
        missing = [k for k in ohaeng if ohaeng[k] == 0]
        return_saju = {
            "일간": f"{day_stem['한글']}{day_stem['오행']}",
            "일간글자": day_stem["한글"],
            "일간오행": day_stem["오행"],
            "월주": pillars["월주"]["한글"] if pillars.get("월주") else "월주",
            "일주": pillars["일주"]["한글"] if pillars.get("일주") else "일주",
            "오행요약": saju["오행 요약"],
            "강한오행": strongest,
            "강한개수": ohaeng[strongest],
            "없는오행": ", ".join(missing) if missing else "없음",
        }
    else:
        return_saju = {
            "일간": "을목", "일간글자": "을", "일간오행": "목",
            "월주": "무진", "일주": "을미",
            "오행요약": "목 2 / 화 0 / 토 5 / 금 1 / 수 0",
            "강한오행": "토", "강한개수": 5, "없는오행": "화, 수",
        }

    if astro:
        return_astro = {
            "sun": astro.get("sun_sign") or "Aries",
            "moon": astro.get("moon_sign") or "Pisces",
            "rising": astro.get("rising_sign") or "Gemini",
        }
    else:
        return_astro = {"sun": "Aries", "moon": "Pisces", "rising": "Gemini"}

    return {
        "이름": name,
        "고민": concern,
        "관계": relationship,
        "커리어": career,
        **return_saju,
        **return_astro,
    }


